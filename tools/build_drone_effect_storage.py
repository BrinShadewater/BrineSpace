#!/usr/bin/env python3
"""Build lossless LA8 storage for the single-colour drone effect sheets.

Each listed sheet holds one colour (135,139,125) or black, with its own alpha. The derived
PNG keeps a binary luminance channel (colour or black) and the original alpha bytes, so
scripts/drone_animation.gd can upload two channels instead of four and supply the colour as
a draw tint. Every RGBA byte of the original must reconstruct exactly, or nothing is written.

Original artwork is only read. The catalog records both hashes: an edited original no longer
matches and the game falls back to it.

  python tools/build_drone_effect_storage.py           # write missing/changed storage + catalog
  python tools/build_drone_effect_storage.py --check   # verify files and catalog, write nothing
"""
import argparse
import hashlib
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "scripts/drone_effect_storage_catalog.gd"
COLOUR = (135, 139, 125)  # Must match the tint in scripts/drone_animation.gd atlas().
# Whole paths on purpose: the release manifest follows whole quoted paths only.
SOURCES = {
    "res://assets/mining-rover-v1-2026-09-26/atlases/mine-west-effects.png":
        "res://assets/mining-rover-v1-2026-09-26/effect-storage/mine-west-effects-la.png",
    "res://assets/mining-rover-v1-2026-09-26/atlases/mine-north-effects.png":
        "res://assets/mining-rover-v1-2026-09-26/effect-storage/mine-north-effects-la.png",
    "res://assets/mining-rover-v1-2026-09-26/atlases/mine-south-effects.png":
        "res://assets/mining-rover-v1-2026-09-26/effect-storage/mine-south-effects-la.png",
}
BAND = 256
Image.MAX_IMAGE_PIXELS = None


def local(path: str) -> Path:
    return ROOT / path[len("res://"):]


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def encode(original: Image.Image) -> np.ndarray:
    """Return the LA array, or raise if the sheet is not strictly one colour or black."""
    width, height = original.size
    encoded = np.empty((height, width, 2), dtype=np.uint8)
    colour = np.array(COLOUR, dtype=np.uint8)
    for y in range(0, height, BAND):
        pixels = np.asarray(original.crop((0, y, width, min(y + BAND, height))))
        lit = pixels[:, :, 0] != 0
        if not np.array_equal(pixels[:, :, :3], lit[:, :, None] * colour):
            raise ValueError("sheet has pixels outside the single effect colour")
        encoded[y:y + pixels.shape[0], :, 0] = lit.astype(np.uint8) * 255
        encoded[y:y + pixels.shape[0], :, 1] = pixels[:, :, 3]
    return encoded


def reconstructs(derived: Image.Image, original: Image.Image) -> bool:
    if derived.mode != "LA" or derived.size != original.size:
        return False
    width, height = original.size
    colour = np.array(COLOUR, dtype=np.uint8)
    for y in range(0, height, BAND):
        box = (0, y, width, min(y + BAND, height))
        data = np.asarray(derived.crop(box))
        pixels = np.asarray(original.crop(box))
        if not np.isin(data[:, :, 0], (0, 255)).all():
            return False
        restored = np.empty_like(pixels)
        restored[:, :, :3] = (data[:, :, 0, None] // 255) * colour
        restored[:, :, 3] = data[:, :, 1]
        if not np.array_equal(restored, pixels):
            return False
    return True


def catalog_text(rows: dict) -> str:
    lines = [
        "extends RefCounted",
        "## Generated by tools/build_drone_effect_storage.py - do not edit by hand.",
        "## Whole paths only. A hash mismatch on either file selects the original sheet.",
        "const DATA={",
    ]
    for source, row in rows.items():
        lines.append(json.dumps(source) + ":" + json.dumps(row, separators=(",", ":")) + ",")
    lines.append("}")
    return "\r\n".join(lines) + "\r\n"


def run(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify only; write nothing")
    args = parser.parse_args(argv)
    rows, problems = {}, []
    for source, target in SOURCES.items():
        source_bytes = local(source).read_bytes()
        with Image.open(io.BytesIO(source_bytes)) as opened:
            original = opened.convert("RGBA")
        width, height = original.size
        target_path = local(target)
        current = target_path.read_bytes() if target_path.exists() else b""
        exact = False
        if current:
            with Image.open(io.BytesIO(current)) as derived:
                exact = reconstructs(derived, original)
        if not exact:
            if args.check:
                problems.append(f"{target}: missing or does not reconstruct {source}")
                continue
            buffer = io.BytesIO()
            Image.fromarray(encode(original)).save(buffer, format="PNG", compress_level=9)
            current = buffer.getvalue()
            with Image.open(io.BytesIO(current)) as derived:
                if not reconstructs(derived, original):
                    raise SystemExit(f"{source}: derived storage failed reconstruction; nothing written")
            target_path.parent.mkdir(parents=True, exist_ok=True)
            target_path.write_bytes(current)
            # Runtime PNG loading: keep the editor from importing the sheet as a texture.
            Path(str(target_path) + ".import").write_text('[remap]\n\nimporter="keep"\n')
            print("wrote", target)
        if local(source).read_bytes() != source_bytes:
            raise SystemExit(f"{source}: original changed during the run")
        rows[source] = {"path": target, "sha256": sha256(current), "width": width, "height": height,
                        "original_sha256": sha256(source_bytes)}
        print(f"{Path(target).name}: exact, {width}x{height}, RGBA {width * height * 4} -> LA {width * height * 2} bytes")
    expected = catalog_text(rows) if not problems else ""
    existing = CATALOG.read_bytes().decode("utf-8") if CATALOG.exists() else ""
    # Line endings differ by checkout; compare content only.
    if not problems and existing.splitlines() != expected.splitlines():
        if args.check:
            problems.append("scripts/drone_effect_storage_catalog.gd does not match the files on disk")
        else:
            CATALOG.write_bytes(expected.encode("utf-8"))
            print("wrote", CATALOG.relative_to(ROOT).as_posix())
    for problem in problems:
        print("FAIL", problem)
    print("DRONE_EFFECT_STORAGE sheets=%d failures=%d" % (len(rows), len(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(run())
