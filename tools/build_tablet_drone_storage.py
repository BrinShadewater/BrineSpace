#!/usr/bin/env python3
"""Build verified, unscaled compact drone sheets for iPad. Original PNGs are read only."""
import argparse, hashlib, io, json
from pathlib import Path
import numpy as np
from PIL import Image
from build_drone_cargo_storage import crop, used_box, reconstructs
ROOT=Path(__file__).resolve().parents[1]
CATALOG=ROOT/'scripts/tablet_drone_storage_catalog.gd'
Image.MAX_IMAGE_PIXELS=None

def main():
    check=argparse.ArgumentParser();check.add_argument('--check',action='store_true');args=check.parse_args()
    records={}
    for name in ['construction','mining','salvage']:
        m=json.loads((ROOT/f'assets/drone-runtime-2026-09-26/{name}.json').read_text())
        for clip in m['states'].values():
            for key in ['atlas','effectAtlas','cargoAtlas']:
                if key in clip: records[clip[key]['path']]=(int(m['frameWidth']),int(m['frameHeight']),int(clip[key]['columns']))
    rows={};total=0;kept=0
    for source,(cw,ch,columns) in sorted(records.items()):
        original=(ROOT/source[6:]).read_bytes();digest=hashlib.sha256(original).hexdigest()
        with Image.open(io.BytesIO(original)) as im:
            width,height=im.size
            if width*height*4<16*1024*1024:continue
            pixels=np.asarray(im.convert('RGBA'))
        if width!=columns*cw or height%ch:raise ValueError(source)
        try:box=used_box(pixels,cw,ch)
        except ValueError:continue
        if box[2]*box[3]>.65*cw*ch:continue
        derived=crop(pixels,box,cw,ch)
        if not reconstructs(derived,pixels,box,cw,ch):raise ValueError('Reconstruction failed: '+source)
        target='res://assets/tablet-drone-storage/'+digest[:16]+'.png';path=ROOT/target[6:]
        if args.check:
            encoded=path.read_bytes()
            with Image.open(io.BytesIO(encoded)) as im:
                if not np.array_equal(np.asarray(im.convert('RGBA')),derived):raise ValueError(target)
        else:
            buffer=io.BytesIO();Image.fromarray(derived).save(buffer,format='PNG');encoded=buffer.getvalue()
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(encoded)
            Path(str(path)+'.import').write_text('[remap]\n\nimporter="keep"\n')
        rows[source]={'path':target,'sha256':hashlib.sha256(encoded).hexdigest(),'original_sha256':digest,'width':width,'height':height,'cell':[cw,ch],'columns':columns,'box':list(box)}
        total+=pixels.nbytes;kept+=derived.nbytes
    text='extends RefCounted\n## Generated by tools/build_tablet_drone_storage.py; original and derived hashes guard fallback.\nconst DATA={\n'+''.join(json.dumps(k)+':'+json.dumps(v,separators=(',',':'))+',\n' for k,v in rows.items())+'}\n'
    if args.check:
        if CATALOG.read_text()!=text:raise ValueError('Catalog differs')
    else:CATALOG.write_text(text)
    print(json.dumps({'sheets':len(rows),'original_decoded_bytes':total,'compact_decoded_bytes':kept,'reduction_percent':round(100*(1-kept/total),2),'all_visible_pixels_exact':True}))
if __name__=='__main__':main()
