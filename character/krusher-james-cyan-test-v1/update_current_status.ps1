$ErrorActionPreference = 'Stop'
$krusherStatusPath = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../docs/CURRENT_STATUS.md'))
$krusherTempPath = Join-Path ([IO.Path]::GetDirectoryName($krusherStatusPath)) 'CURRENT_STATUS.krusher-james-cyan.tmp'
$krusherInput = $null
$krusherOutput = $null
try {
    # Preserve the large concurrent status file byte-for-byte. Deny writers while
    # copying; permit atomic replacement so the original cannot be partly written.
    $krusherInput = [IO.FileStream]::new($krusherStatusPath, [IO.FileMode]::Open, [IO.FileAccess]::Read, ([IO.FileShare]::Read -bor [IO.FileShare]::Delete))
    $krusherOutput = [IO.FileStream]::new($krusherTempPath, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
    $krusherHeader = @'
## Krusher James body muted cyan recolour trial - October 2, 2026

character/krusher-james-cyan-test-v1 adds 148 south idle/walk recoloured PNGs,
per-frame marking masks and a Bill/James cyan comparison. Only preserved yellow
upper suit pixels changed; source head, alpha and lower tool colours retained.
Matte cyan RGB82/124/128, source shading capped at1.15. 444 composition, 756
independent fidelity and 446 existing-consumer native checks pass. Godot exit0
5.00s; scratch APPDATA/all2,930 owner files unchanged. Comparison sheets viewed.
7.5s source-derived before/after MP4 retained, no temporal acceptance claimed.
Other directions/helmets unchecked. Current Bill/normal selectors unchanged.
See candidate HANDOFF.md for source scope and remaining family work.

'@
    $krusherBytes = [Text.UTF8Encoding]::new($false).GetBytes($krusherHeader + "`n")
    $krusherOutput.Write($krusherBytes, 0, $krusherBytes.Length)
    $krusherInput.CopyTo($krusherOutput)
    $krusherOutput.Flush($true)
    $krusherOutput.Dispose()
    $krusherOutput = $null
    [IO.File]::Replace($krusherTempPath, $krusherStatusPath, [NullString]::Value)
    Write-Output 'CURRENT_STATUS.md updated atomically; previous content preserved.'
} finally {
    if ($null -ne $krusherOutput) { $krusherOutput.Dispose() }
    if ($null -ne $krusherInput) { $krusherInput.Dispose() }
}
